local loader = require("helpers.load_addon")

describe("DB migration", function()
  it("initializes schema version 8 with canonical dispute projections", function()
    local _, dibs = loader.load({ wow = { guildLeader = true } })
    local db = dibs.GetDB()
    assert_equal(8, db.version)
    assert_not_nil(db.permissions)
    assert_not_nil(db.ledger.awardTransactions)
    assert_not_nil(db.preDibs.acquisitions)
    assert_not_nil(db.disputes)
    assert_not_nil(db.disputes.requests)
    assert_equal(3, db.disputes.version)
    assert_not_nil(db.disputes.operationStates)
  end)
end)
